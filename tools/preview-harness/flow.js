const { chromium } = require('playwright');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 844 } });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', (e) => errs.push(e.message));
  await p.goto('file://' + require('path').join(__dirname, 'out') + '/enquiry.html?category=Beds&product=Noor%20bed&utm_source=google&utm_campaign=test');
  await p.evaluate(() => {
    window.__events = [];
    document.addEventListener('aaf:track', (e) => window.__events.push(e.detail.name));
    document.querySelector('[data-enquiry-form]').addEventListener('submit', (e) => {
      if (e.defaultPrevented) return;
      e.preventDefault();
      window.__submitted = Object.fromEntries(new FormData(e.target));
    });
  });
  const active = () => p.evaluate(() => document.querySelector('.enquiry-step.is-active').dataset.step);
  const visibleErrors = () => p.evaluate(() => Array.from(document.querySelectorAll('.field__error')).filter((e) => !e.hidden).map((e) => e.textContent.trim()));
  console.log('start step', await active(), 'prefilled category:', await p.evaluate(() => (document.querySelector('[name="contact[Category]"]:checked') || {}).value));
  // clear category to test validation
  await p.evaluate(() => document.querySelectorAll('[name="contact[Category]"]').forEach((i) => (i.checked = false)));
  await p.click('[data-next]');
  console.log('after empty continue: step', await active(), 'errors', await visibleErrors());
  await p.click('label[for$="-cat-3"]');
  await p.click('[data-next]');
  console.log('step', await active(), 'visible type groups', await p.evaluate(() => Array.from(document.querySelectorAll('[data-types-for].is-visible')).map((g) => g.dataset.typesFor)));
  await p.click('[data-types-for="beds"] label >> nth=2');
  await p.click('[data-next]');
  console.log('step', await active());
  await p.fill('[name="contact[Width]"]', '-5');
  await p.click('[data-next]');
  console.log('negative width -> step', await active(), await visibleErrors());
  await p.fill('[name="contact[Width]"]', '200');
  await p.fill('[name="contact[Depth]"]', '180');
  await p.click('label[for$="-unit-in"]');
  await p.click('[data-next]');
  await p.click('label[for$="-mat-1"]');
  await p.click('.choice-grid--pills label[for$="-fin-1"]');
  await p.click('[data-next]');
  await p.click('label[for$="-col-1"]');
  await p.click('label[for$="-col-4"]');
  await p.click('label[for$="-uph-2"]');
  await p.click('[data-next]');
  await p.fill('[name="contact[Reference link 1]"]', 'not a url');
  await p.click('[data-next]');
  console.log('bad url -> step', await active(), await visibleErrors());
  await p.fill('[name="contact[Reference link 1]"]', 'https://pinterest.com/board');
  await p.click('[data-next]');
  await p.click('[data-next]');
  console.log('empty body -> step', await active(), await visibleErrors());
  await p.fill('[name="contact[body]"]', 'King bed for main bedroom, low headboard.');
  await p.selectOption('[name="contact[Budget]"]', { index: 1 });
  await p.click('[data-next]');
  await p.fill('[name="contact[name]"]', 'Test Customer');
  await p.fill('[name="contact[email]"]', 'bad@');
  await p.fill('[name="contact[phone]"]', '12');
  await p.click('[data-next]');
  console.log('bad contact -> step', await active(), await visibleErrors());
  await p.fill('[name="contact[email]"]', 'test@example.com');
  await p.fill('[name="contact[phone]"]', '+91 98000 00000');
  await p.click('[data-next]');
  console.log('step', await active(), 'submit visible', await p.isVisible('[data-submit]'));
  console.log('review:', await p.evaluate(() => Array.from(document.querySelectorAll('.enquiry-review__row')).map((r) => r.querySelector('dt').textContent + ': ' + r.querySelector('dd').textContent.replace(/\n/g, ' | '))));
  await p.screenshot({ path: '' + require('path').join(__dirname, 'shots') + '/flow-review-mobile.png', fullPage: false });
  // back edit
  await p.click('.enquiry-review__edit >> nth=2');
  console.log('edit dims -> step', await active());
  await p.click('[data-next]');
  for (let i = 0; i < 5; i++) await p.click('[data-next]');
  await p.click('[data-submit]');
  await p.waitForTimeout(200);
  console.log('submitted:', JSON.stringify(await p.evaluate(() => window.__submitted), null, 0));
  console.log('button loading', await p.evaluate(() => document.querySelector('[data-submit]').classList.contains('is-loading')));
  console.log('events', await p.evaluate(() => [...new Set(window.__events)]));
  // draft restore
  const p2 = await ctx.newPage();
  await p2.goto('file://' + require('path').join(__dirname, 'out') + '/enquiry.html');
  console.log('restored step', await p2.evaluate(() => document.querySelector('.enquiry-step.is-active').dataset.step), 'restored name', await p2.inputValue('[name="contact[name]"]'));
  console.log('errors', errs);
  await b.close();
})();
